function traducirPapel(p: string): string {
  return p.split(' ').map((w) => {
    const d = w.match(/^d['’](.+)$/);
    return d ? `de ${PALABRAS_PAPELES[d[1]] ?? d[1]}` : (PALABRAS_PAPELES[w] ?? w);
  }).join(' ');
}

